#!/usr/bin/env python3
"""Design each antenna's T-match from its simulated impedance.

Reads results/<name>.csv (f_MHz, S11_dB, Re_Zin, Im_Zin from sim_antenna.py),
picks an L-section (S1 = 0R selector + shunt + series S2, or shunt + S1 with
S2 = 0R) using standard E12/E24 values, then writes match.py and a plot of
S11 before/after matching (results/match.png).

The match is computed at the feed; the parts sit within ~3 mm of it.
"""

import csv
import itertools
import math
import os

import numpy as np

from antenna_geometry import FREQ_MHZ, NAMES

HERE = os.path.dirname(os.path.abspath(__file__))
Z0 = 50.0

E24 = [1.0, 1.1, 1.2, 1.3, 1.5, 1.6, 1.8, 2.0, 2.2, 2.4, 2.7, 3.0, 3.3, 3.6, 3.9, 4.3,
       4.7, 5.1, 5.6, 6.2, 6.8, 7.5, 8.2, 9.1]
E12 = [1.0, 1.2, 1.5, 1.8, 2.2, 2.7, 3.3, 3.9, 4.7, 5.6, 6.8, 8.2]
CAPS = sorted({round(v * 10 ** d, 2) for v in E24 for d in (-1, 0, 1, 2)
               if 0.5 <= v * 10 ** d <= 100})               # pF, 0603 C0G
INDS = sorted({round(v * 10 ** d, 1) for v in E12 for d in (0, 1, 2)
               if 1.0 <= v * 10 ** d <= 390})               # nH, 0603 wire-wound
Q_L, Q_C = 40.0, 300.0      # realistic 0603 part Q at 300-900 MHz

REFS = {"433": ("R301", "C301", "L301"), "315": ("R311", "C311", "L311"),
        "868": ("R321", "C321", "L321"), "915": ("R331", "C331", "L331")}
DEFAULT_FITTED = {"433", "868"}   # radio A ships on 433, radio B on 868


def load(name):
    f, zr, zi = [], [], []
    with open(os.path.join(HERE, "results", f"{name}.csv")) as fh:
        for row in csv.DictReader(fh):
            f.append(float(row["f_MHz"]) * 1e6)
            zr.append(float(row["Re_Zin"]))
            zi.append(float(row["Im_Zin"]))
    return np.array(f), np.array(zr) + 1j * np.array(zi)


def z_part(kind, val, f):
    w = 2 * np.pi * f
    if kind == "0R":
        return np.zeros_like(f) + 1e-3
    if kind == "C":
        x = 1 / (w * val * 1e-12)
        return x / Q_C - 1j * x
    if kind == "L":
        x = w * val * 1e-9
        return x / Q_L + 1j * x
    raise ValueError(kind)


def label(kind, val):
    if kind == "0R":
        return "0R"
    if kind == "C":
        return f"{val:g}pF"
    return f"{val:g}nH"


def network(zl, f, s1, sh, s2):
    """Z seen from the node: S1 series, then shunt, then S2 series, then load."""
    z = zl + z_part(*s2, f)
    ysh = 1 / z_part(*sh, f)
    z = 1 / (1 / z + ysh)
    return z + z_part(*s1, f)


def match_eff(zl, f, s1, sh, s2):
    """Fraction of the power entering the network that reaches the antenna."""
    zin = network(zl, f, s1, sh, s2)
    i1 = 1 / zin                           # 1 V at the input
    vm = 1 - i1 * z_part(*s1, f)
    i2 = vm / (z_part(*s2, f) + zl)
    return (np.abs(i2) ** 2 * zl.real) / np.real(1 / np.conj(zin))


def gamma(z):
    return (z - Z0) / (z + Z0)


def design(name):
    f, zl = load(name)
    f0 = FREQ_MHZ[name] * 1e6
    band = (f > f0 * 0.99) & (f < f0 * 1.01)
    series = [("0R", 0)] + [("C", c) for c in CAPS] + [("L", l) for l in INDS]
    shunts = [("C", c) for c in CAPS] + [("L", l) for l in INDS]
    best = None
    # L-sections: (S1 = 0R, shunt, S2) or (S1, shunt, S2 = 0R)
    for sh, s in itertools.product(shunts, series):
        for s1, s2 in ((("0R", 0), s), (s, ("0R", 0))):
            g = np.abs(gamma(network(zl[band], f[band], s1, sh, s2)))
            score = float(np.max(g))
            if best is None or score < best[0]:
                best = (score, s1, sh, s2)
    _, s1, sh, s2 = best
    gm = np.abs(gamma(network(zl, f, s1, sh, s2)))
    i0 = int(np.argmin(np.abs(f - f0)))
    bw = f[gm < 10 ** (-10 / 20)]
    eff = match_eff(zl[i0:i0 + 1], f[i0:i0 + 1], s1, sh, s2)[0]
    return {
        "f": f, "zl": zl, "gm": gm, "f0": f0, "z0": zl[i0], "eff": float(eff),
        "s1": s1, "sh": sh, "s2": s2,
        "s11_0": 20 * math.log10(gm[i0]),
        "bw10": (bw.min() / 1e6, bw.max() / 1e6) if len(bw) else None,
    }


def main():
    results = {n: design(n) for n in NAMES}
    lines = ['"""T-match part values per antenna, generated by design_match.py from the',
             'openEMS results in results/ (do not edit by hand).',
             '',
             'Each branch is: S1 (series, selector) -> C (shunt to GND) -> S2 (series)',
             '-> antenna. S1 fitted = antenna selected. "DNP" = leave the pads empty.',
             '"""', '', 'MATCH = {']
    for n in NAMES:
        r = results[n]
        s1 = label(*r["s1"])
        sel = s1 if n in DEFAULT_FITTED else f"DNP ({s1} to use)"
        lines.append(f'    "{n}": {{"refs": {REFS[n]!r}, "s1": {sel!r}, '
                     f'"c": {label(*r["sh"])!r}, "s2": {label(*r["s2"])!r},')
        lines.append(f'            "z_ant": "{r["z0"].real:.1f}{r["z0"].imag:+.1f}j", '
                     f'"s11_db": {r["s11_0"]:.1f}, "bw10_mhz": {r["bw10"]!r}}},')
        print(f'{n}: Zant={r["z0"]:.1f}  S1={s1} shunt={label(*r["sh"])} '
              f'S2={label(*r["s2"])}  S11={r["s11_0"]:.1f} dB  '
              f'-10dB band={r["bw10"]}  match loss={-10*math.log10(max(r["eff"],1e-6)):.1f} dB')
    lines.append("}")
    open(os.path.join(HERE, "match.py"), "w").write("\n".join(lines) + "\n")

    from antenna_geometry import PARAMS, arm_length
    md = ["# Antenna results (openEMS)", "",
          "| Antenna | Arm (mm) | Tap / tail (mm) | Z at f0 (ohm) | S11 unmatched | "
          "T-match S1 / shunt / S2 | S11 matched | -10 dB band (MHz) | match loss |",
          "|---|---|---|---|---|---|---|---|---|"]
    for n in NAMES:
        r = results[n]
        i0 = int(np.argmin(np.abs(r["f"] - r["f0"])))
        raw = 20 * math.log10(abs(gamma(r["zl"][i0])))
        bw = f'{r["bw10"][0]:.0f}-{r["bw10"][1]:.0f}' if r["bw10"] else "-"
        md.append(f'| {n} MHz | {arm_length(n):.0f} | {PARAMS[n]["tap"]:g} / '
                  f'{PARAMS[n]["tail"]:g} | {r["z0"].real:.1f}{r["z0"].imag:+.1f}j | '
                  f'{raw:.1f} dB | {label(*r["s1"])} / {label(*r["sh"])} / '
                  f'{label(*r["s2"])} | {r["s11_0"]:.1f} dB | {bw} | '
                  f'{-10 * math.log10(max(r["eff"], 1e-6)):.1f} dB |')
    open(os.path.join(HERE, "results", "summary.md"), "w").write("\n".join(md) + "\n")

    try:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt
    except ImportError:
        return
    fig, axes = plt.subplots(2, 2, figsize=(10, 7))
    for ax, n in zip(axes.flat, NAMES):
        r = results[n]
        fm = r["f"] / 1e6
        ax.plot(fm, 20 * np.log10(np.abs(gamma(r["zl"]))), label="antenna alone")
        ax.plot(fm, 20 * np.log10(r["gm"]), label="with T-match")
        ax.axvline(r["f0"] / 1e6, color="gray", ls=":")
        ax.axhline(-10, color="gray", ls="--", lw=0.8)
        ax.set_title(f"{n} MHz IFA")
        ax.set_xlabel("MHz")
        ax.set_ylabel("S11 (dB)")
        ax.set_ylim(-35, 0)
        ax.set_xlim(r["f0"] / 1e6 * 0.85, r["f0"] / 1e6 * 1.15)
        ax.grid(alpha=0.3)
        ax.legend(fontsize=8)
    fig.tight_layout()
    fig.savefig(os.path.join(HERE, "results", "match.png"), dpi=110)


if __name__ == "__main__":
    main()
